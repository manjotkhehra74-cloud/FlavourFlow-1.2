const DICTIONARIES = { pa, hi, en: {} };

let active = 'en';
/**
 * Resolves the active dictionary. It runs at import time so module-level `t()` calls in
 * the page modules are already translated; changing the language reloads the page.
 */
export function loadLanguage(language = getPrefs().language) {
  active = DICTIONARIES[language] ? language : 'en';
  return active;
}
loadLanguage();

export const currentLanguage = () => active;

/**
 * Translates `text`, falling back to the English source. `vars` interpolates `{name}`
 * placeholders so translators can move them around freely.
 */
export function t(text, vars) {
  const translated = DICTIONARIES[active]?.[text] ?? text;
  if (!vars) return translated;
  return translated.replace(/\{(\w+)\}/g, (match, key) => (key in vars ? String(vars[key]) : match));
}

/** Locale tag for Intl formatting — Punjabi and Hindi both use Indian conventions. */
export const localeTag = () => ({ pa: 'pa-IN', hi: 'hi-IN', en: 'en-IN' })[active] || 'en-IN';
